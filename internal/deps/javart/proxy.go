package javart

import (
	"fmt"
	"reflect"
)

// Method mirrors java.lang.reflect.Method as an InvocationHandler sees it: a
// name, and the ability to invoke it on a target.
//
// The name is the one the original declared, because that is what a handler
// prints; the call it forwards resolves the Go method behind it.
type Method struct {
	name   string
	target reflect.Value
}

// GetName returns the method's name.
func (m Method) GetName() string { return m.name }

// Invoke calls the method on target with args and returns its results.
// Passing a target of nil invokes it on the target the Method was bound to,
// which is what Method.invoke(target, args) does in the original.
func (m Method) Invoke(target any, args ...any) ([]any, error) {
	recv := m.target
	if target != nil {
		recv = reflect.ValueOf(target)
	}
	fn := recv.MethodByName(GoMethodName(m.name))
	if !fn.IsValid() {
		return nil, fmt.Errorf("javart: no method %s on %s", m.name, recv.Type())
	}
	in := make([]reflect.Value, len(args))
	for i, a := range args {
		if a == nil {
			in[i] = reflect.Zero(fn.Type().In(i))
			continue
		}
		in[i] = reflect.ValueOf(a)
	}
	out := fn.Call(in)
	results := make([]any, len(out))
	for i, o := range out {
		results[i] = o.Interface()
	}
	return results, nil
}

// InvocationHandler mirrors java.lang.reflect.InvocationHandler.
type InvocationHandler interface {
	Invoke(proxy any, method Method, args []any) ([]any, error)
}

// InvocationDispatcher routes an interface method call to an
// InvocationHandler, resolving the named method against the target.
//
// This is the half of java.lang.reflect.Proxy that Go can express. The other
// half — synthesising, at run time, a type that implements a given interface —
// Go cannot do: interface satisfaction is decided by the compiler. The
// adapters that would have been generated bytecode are therefore written out
// next to the interface they proxy (see internal/proxy). Their behaviour is
// the same: every interface method goes through the handler, and a call the
// target makes on itself does not.
type InvocationDispatcher struct {
	target  any
	handler InvocationHandler
}

// NewInvocationDispatcher binds a handler to a target.
func NewInvocationDispatcher(target any, handler InvocationHandler) *InvocationDispatcher {
	return &InvocationDispatcher{target: target, handler: handler}
}

// Target returns the object the proxy stands in front of.
func (d *InvocationDispatcher) Target() any { return d.target }

// Dispatch runs the named method through the handler, as a generated proxy
// method body would.
func (d *InvocationDispatcher) Dispatch(proxy any, name string, args ...any) ([]any, error) {
	m := Method{name: name, target: reflect.ValueOf(d.target)}
	return d.handler.Invoke(proxy, m, args)
}
